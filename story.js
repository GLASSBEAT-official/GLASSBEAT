function parseStoryScript(script) {
  const tokens = [];
  const regex = /(\[[\s\S]*?\]|\{[\s\S]*?\})/g;
  let match;

  while ((match = regex.exec(script)) !== null) {
    const raw = match[0];

    if (raw.startsWith("[")) {
      tokens.push({
        type: "text",
        text: raw
          .slice(1, -1)
          .trim()
          .split("/")
          .map(line => line.trim())
          .join("\n")
      });
    } else if (raw.startsWith("{")) {
      tokens.push({
        type: "command",
        command: raw.slice(1, -1).trim()
      });
    }
  }

  return tokens;
}

function updateStoryTextPosition(text) {
  const previousText = storyText.textContent;

  storyText.style.visibility = "hidden";
  storyText.textContent = text;

  const textHeight = storyText.offsetHeight;
  const top = Math.max(48, (window.innerHeight - textHeight) / 2);

  storyText.style.top = top + "px";
  storyText.textContent = previousText;
  storyText.style.visibility = "";
}

function typeText(text) {
  clearInterval(typingTimer);

  if (Array.isArray(text)) {
    text = text.join("\n");
  }

  updateStoryTextPosition(text);

  fullText = text;
  storyText.textContent = "";
  isTyping = true;

  let index = 0;

  typingTimer = setInterval(() => {
    storyText.textContent += text[index];
    index++;

    if (index >= text.length) {
      clearInterval(typingTimer);
      isTyping = false;
    }
  }, 38);
}

function getEpisodeSteps(episode) {
  if (episode.script) return parseStoryScript(episode.script);

  if (episode.lines) {
    return episode.lines.map(line => ({
      type: "text",
      text: Array.isArray(line) ? line.join("\n") : line
    }));
  }

  return [];
}

