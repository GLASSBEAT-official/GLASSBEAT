function getPreviousStoryEpisode(chapterIndex, episodeIndex, isFragment = false) {
  const chapter = chapters[chapterIndex];
  const episodes = isFragment ? (chapter.fragmentEpisodes || []) : chapter.episodes;

  if (episodeIndex > 0) return episodes[episodeIndex - 1];
  if (isFragment && chapter.episodes.length > 0) return chapter.episodes.at(-1);

  for (let index = chapterIndex - 1; index >= 0; index--) {
    const previousEpisodes = chapters[index].episodes || [];
    if (previousEpisodes.length > 0) return previousEpisodes.at(-1);
  }

  return null;
}

