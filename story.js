function preloadImageAssets(urls, timeoutMs = 12000) {
  const uniqueUrls = [...new Set(urls.filter(Boolean))];
  if (uniqueUrls.length === 0) return Promise.resolve();

  const imagePromises = uniqueUrls.map(url => new Promise(resolve => {
    const image = new Image();
    image.onload = resolve;
    image.onerror = resolve;
    image.src = url;
    if (image.complete) resolve();
  }));

  return Promise.race([
    Promise.all(imagePromises),
    new Promise(resolve => setTimeout(resolve, timeoutMs))
  ]);
}

function hideAssetLoadingScreen() {
  const loadingScreen = document.getElementById("assetLoadingScreen");
  if (!loadingScreen) return;

  loadingScreen.classList.add("loaded");
  setTimeout(() => loadingScreen.remove(), 400);
}

function preloadStoryImages() {
  const urls = [
    "assets/bg/story_bg.jpg",
    "assets/bg/select_bg.jpg",
    "assets/bg/episode_button.png",
    "assets/bg/episode_button_2_4.png",
    "assets/bg/episode_button_3_10.png",
    "images/story/2_3_after.png",
    "images/partners/isabel_full.png"
  ];

  for (const chapter of chapters) {
    if (chapter.background) urls.push(chapter.background);

    const episodes = [
      ...(chapter.episodes || []),
      ...(chapter.fragmentEpisodes || [])
    ];

    for (const episode of episodes) {
      const script = String(episode.script || "");
      for (const match of script.matchAll(/\{image:([^}]+)\}/g)) {
        urls.push(match[1].trim());
      }
    }
  }

  urls.push(...Array.from(document.images, image => image.currentSrc || image.src));
  return preloadImageAssets(urls);
}

