let storyBGM = null;
let currentBgmSrc = null;
let bgmFadeTimer = null;

function startStoryBGM() {
  playStoryBGM("sounds/story_bgm.mp3", 0.45);
}

function stopStoryBGM(fadeMs = 900) {
  if (!storyBGM) return;

  if (bgmFadeTimer) {
    clearInterval(bgmFadeTimer);
    bgmFadeTimer = null;
  }

  const audio = storyBGM;
  const startVolume = audio.volume;
  const intervalMs = 50;
  const steps = Math.max(1, Math.ceil(fadeMs / intervalMs));
  let currentStep = 0;

  bgmFadeTimer = setInterval(() => {
    currentStep++;

    const progress = currentStep / steps;
    audio.volume = Math.max(0, startVolume * (1 - progress));

    if (currentStep >= steps) {
      clearInterval(bgmFadeTimer);
      bgmFadeTimer = null;

      audio.pause();
      audio.currentTime = 0;
      audio.volume = startVolume;

      if (storyBGM === audio) {
        storyBGM = null;
        currentBgmSrc = null;
      }
    }
  }, intervalMs);
}

window.addEventListener("DOMContentLoaded", () => {
  startStoryBGM();
});

function playStoryBGM(src = "sounds/story_bgm.mp3", volume = 0.45) {
  if (storyBGM && currentBgmSrc === src && !storyBGM.paused) {
    storyBGM.volume = volume;
    return;
  }

  if (bgmFadeTimer) {
    clearInterval(bgmFadeTimer);
    bgmFadeTimer = null;
  }

   if (storyBGM) {
    storyBGM.pause();
    storyBGM.currentTime = 0;
  }

  storyBGM = new Audio(src);
  currentBgmSrc = src;
  storyBGM.loop = true;
  storyBGM.volume = volume;

  storyBGM.play().catch(() => {
    document.addEventListener("click", () => {
      storyBGM.play();
    }, { once: true });
  });
}

