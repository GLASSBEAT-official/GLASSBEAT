function isEpisodeUnlocked(episode) {
  if (!episode.unlock) return true;

  if (episode.unlock.type === "songPlayed") {
    return hasPlayedSong(episode.unlock.song);
  }

  if (episode.unlock.type === "storyRead") {
    return hasReadStory(episode.unlock.storyId);
  }

  if (episode.unlock.type === "storyReadAndSongPlayed") {
    return (
      hasReadStory(episode.unlock.storyId) &&
      hasPlayedSong(episode.unlock.song)
    );
  }

  return false;
}

