async function runStoryCommand(command) {
  const parts = command.split(":");
  const name = parts[0];

  if (name === "bgm" && parts[1] === "stop") {
    const fadeMs = Number(parts[2] || 900);
    stopStoryBGM(fadeMs);
    return;
  }

  if (name === "bgm" && parts[1] === "play") {
    const src = parts[2] || "sounds/story_bgm.mp3";
    const volume = Number(parts[3] || 0.45);
    playStoryBGM(src, volume);
    return;
  }

  if (name === "wait") {
    const ms = Number(parts[1] || 0);
    await waitMs(ms);
    return;
  }
}

