let storyBGM = null;
let currentBgmSrc = null;
let bgmFadeTimer = null;

function startStoryBGM() {
  playStoryBGM("sounds/story_bgm.mp3", 0.45);
}

function stopStoryBGM(fadeMs = 900) {
  if (!storyBGM) return;

  if (bgmFadeTimer) {
    clearInterval(bgmFadeTimer);
    bgmFadeTimer = null;
  }

  const audio = storyBGM;
  const startVolume = audio.volume;
  const intervalMs = 50;
  const steps = Math.max(1, Math.ceil(fadeMs / intervalMs));
  let currentStep = 0;

  bgmFadeTimer = setInterval(() => {
    currentStep++;

    const progress = currentStep / steps;
    audio.volume = Math.max(0, startVolume * (1 - progress));

    if (currentStep >= steps) {
      clearInterval(bgmFadeTimer);
      bgmFadeTimer = null;

      audio.pause();
      audio.currentTime = 0;
      audio.volume = startVolume;

      if (storyBGM === audio) {
        storyBGM = null;
        currentBgmSrc = null;
      }
    }
  }, intervalMs);
}

window.addEventListener("DOMContentLoaded", () => {
  startStoryBGM();
});

function playStoryBGM(src = "sounds/story_bgm.mp3", volume = 0.45) {
  if (storyBGM && currentBgmSrc === src && !storyBGM.paused) {
    storyBGM.volume = volume;
    return;
  }

  if (bgmFadeTimer) {
    clearInterval(bgmFadeTimer);
    bgmFadeTimer = null;
  }

  storyBGM = new Audio(src);
  currentBgmSrc = src;
  storyBGM.loop = true;
  storyBGM.volume = volume;

  storyBGM.play().catch(() => {
    document.addEventListener("click", () => {
      storyBGM.play();
    }, { once: true });
  });
}

function waitMs(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function runStoryCommand(command) {
  const parts = command.split(":");
  const name = parts[0];

  if (name === "bgm" && parts[1] === "stop") {
    const fadeMs = Number(parts[2] || 900);
    stopStoryBGM(fadeMs);
    return;
  }

  if (name === "bgm" && parts[1] === "play") {
    const src = parts[2] || "sounds/story_bgm.mp3";
    const volume = Number(parts[3] || 0.45);
    playStoryBGM(src, volume);
    return;
  }

  if (name === "wait") {
    const ms = Number(parts[1] || 0);
    await waitMs(ms);
    return;
  }
}

let isAdvancingStory = false;

async function showCurrentStep() {
  if (isAdvancingStory) return;
  isAdvancingStory = true;

  const episode = chapters[currentChapterIndex].episodes[currentEpisodeIndex];
  const steps = getEpisodeSteps(episode);

  while (currentLineIndex < steps.length) {
    const step = steps[currentLineIndex];

    if (step.type === "command") {
      await runStoryCommand(step.command);
      currentLineIndex++;
      continue;
    }

    typeText(step.text);
    updateReadingPrevButton();
    isAdvancingStory = false;
    return;
  }

  markEpisodeRead();

  if (episode.id === "chapter1_episode6") {
  const fade = document.getElementById("storyIntroFade");
  if (fade) {
    fade.classList.remove("fadeIn");
    fade.classList.add("fadeOut");
  }

  setTimeout(() => {
    location.href = "title.html?endingDemo=1";
  }, 900);

  return;
}
  closeEpisode();
  renderEpisodes();
  isAdvancingStory = false;
}

