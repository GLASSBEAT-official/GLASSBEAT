window.researchRecordsState = {
  getRewardRecordIds(reward) {
    const value = reward?.researchRecords ?? reward?.researchRecord;
    const ids = Array.isArray(value) ? value : value ? [value] : [];
    return [...new Set(ids.map(id => String(id).trim()).filter(Boolean))];
  },

  getUnlockedRecords(records = window.researchRecordsData?.records || [], mapData = null) {
    if (!mapData || !Array.isArray(mapData.pieces)) return [...records];
    const assignedIds = new Set();
    const unlockedRewardIds = new Set();
    const saveData = (() => {
      try {
        return JSON.parse(localStorage.getItem("rhythmGame") || "{}");
      } catch {
        return {};
      }
    })();
    const clearedPieceIds = new Set(saveData.mapProgress?.[mapData.id]?.clearedPieces || []);

    for (const piece of mapData.pieces) {
      const rewardIds = this.getRewardRecordIds(piece.reward);
      rewardIds.forEach(id => assignedIds.add(id));
      if (clearedPieceIds.has(piece.id)) {
        rewardIds.forEach(id => unlockedRewardIds.add(id));
      }
    }

    return records.filter(record => {
      const id = String(record?.id || "").trim();
      return id && (!assignedIds.has(id) || unlockedRewardIds.has(id));
    });
  },

  getReadIds() {
    try {
      const saveData = JSON.parse(localStorage.getItem("rhythmGame") || "{}");
      return new Set(Array.isArray(saveData.readResearchRecordIds) ? saveData.readResearchRecordIds : []);
    } catch {
      return new Set();
    }
  },

  markRead(recordId) {
    if (!recordId) return;
    let saveData;
    try {
      saveData = JSON.parse(localStorage.getItem("rhythmGame") || "{}");
    } catch {
      saveData = {};
    }
    const readIds = new Set(Array.isArray(saveData.readResearchRecordIds) ? saveData.readResearchRecordIds : []);
    readIds.add(recordId);
    saveData.readResearchRecordIds = [...readIds];
    localStorage.setItem("rhythmGame", JSON.stringify(saveData));
  },

  hasUnread(records = window.researchRecordsData?.records || []) {
    const readIds = this.getReadIds();
    return records.some(record => record?.id && !readIds.has(record.id));
  }
};

